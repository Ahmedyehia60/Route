-- RouteFlow database schema (PostgreSQL)
-- Run on a fresh database to create the tables used by authentication and shipments.
-- Existing tables are left as they are; this script does not alter or delete them.

BEGIN;

-- Authentication and user management
CREATE TABLE IF NOT EXISTS roles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role_id INTEGER NOT NULL REFERENCES roles(id),
  status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
  created_by INTEGER REFERENCES users(id),
  failed_login_attempts INTEGER NOT NULL DEFAULT 0,
  lockout_until TIMESTAMPTZ,
  password_changed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT users_failed_login_attempts_nonnegative
    CHECK (failed_login_attempts >= 0)
);

CREATE TABLE IF NOT EXISTS refresh_tokens (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash VARCHAR(64) NOT NULL UNIQUE,
  ip_address VARCHAR(45),
  user_agent TEXT,
  expires_at TIMESTAMPTZ NOT NULL,
  is_revoked BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS refresh_tokens_user_id_idx
  ON refresh_tokens(user_id);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash VARCHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  failed_attempts INTEGER NOT NULL DEFAULT 0,
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT password_reset_failed_attempts_nonnegative
    CHECK (failed_attempts >= 0)
);

CREATE INDEX IF NOT EXISTS password_reset_tokens_user_id_idx
  ON password_reset_tokens(user_id);

-- Carriers and transport documents
CREATE TABLE IF NOT EXISTS carriers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS bills_of_lading (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bol_number VARCHAR(50) NOT NULL UNIQUE,
  carrier_id INTEGER REFERENCES carriers(id),
  issue_date DATE NOT NULL,
  origin VARCHAR(200) NOT NULL,
  destination VARCHAR(200) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
    CHECK (status IN ('ACTIVE', 'CANCELLED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Shipments. One BOL can be linked to many shipments.
CREATE TABLE IF NOT EXISTS shipments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tracking_number VARCHAR(50) NOT NULL UNIQUE,
  bill_of_lading_id INTEGER REFERENCES bills_of_lading(id),
  shipper_name VARCHAR(150) NOT NULL,
  shipper_origin VARCHAR(200) NOT NULL,
  consignee_name VARCHAR(150) NOT NULL,
  consignee_destination VARCHAR(200) NOT NULL,
  cargo_class VARCHAR(100),
  cargo_description TEXT,
  weight_kg NUMERIC(10, 2) CHECK (weight_kg IS NULL OR weight_kg >= 0),
  carrier_id INTEGER REFERENCES carriers(id),
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING_INTAKE'
    CHECK (status IN (
      'PENDING_INTAKE',
      'STAGED',
      'IN_TRANSIT',
      'ON_HOLD',
      'OUT_FOR_DELIVERY',
      'DELIVERED'
    )),
  current_location VARCHAR(200),
  sla_due_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS shipments_bol_id_idx
  ON shipments(bill_of_lading_id);

CREATE INDEX IF NOT EXISTS shipments_status_idx
  ON shipments(status);

CREATE INDEX IF NOT EXISTS shipments_carrier_id_idx
  ON shipments(carrier_id);

COMMIT;
